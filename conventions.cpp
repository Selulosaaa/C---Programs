#include <iostream>

// this is how to naming convention in c++
// naming convention is a set of rules for naming variables, functions, classes, and other identifiers in a programming language.
int main() {
    int nama_orang = 5; // this is a snake_case because it use a underscore to separate words
    int NamaOrang = 3; // this is a PascalCase because it use a capital letter to separate words
    int namaOrang = 2; // this is a camelCase because it use a capital letter to separate words but the first letter is lowercase
    int iNamaOrang = 1; // this is a Hungarian notation because it use a prefix to indicate the type of the variable
    return 0;
}